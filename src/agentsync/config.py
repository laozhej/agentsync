@dataclass
class AgentSyncConfig:
    """Parsed agentsync configuration."""

    version: str = "1.0.0"
    canonical: str = RULES_FILE
    tools: list[str] = field(
        default_factory=lambda: [
            "agents_md",
            "claude_md",
            "cursorrules",
            "cursor_mdc",
            "copilot",
            "gemini_md",
            "windsurf",
        ]
    )
    auto_gitignore: bool = True
    warn_unmanaged: bool = True
    root: Path = field(default_factory=Path.cwd)

    @property
    def canonical_path(self) -> Path:
        return self.root / self.canonical

    @property
    def config_path(self) -> Path:
        return self.root / CONFIG_FILE

    @property
    def lock_path(self) -> Path:
        return self.root / LOCK_FILE

    def __repr__(self) -> str:
        return f"AgentSyncConfig(tools={self.tools}, canonical={self.canonical!r})"


def load_config(root: Path | None = None) -> AgentSyncConfig:
    """Load agentsync config from .agentsync/config.toml."""
    root = root or Path.cwd()
    config_path = root / CONFIG_FILE
    cfg = AgentSyncConfig(root=root)

    if not config_path.exists():
        return cfg

    if tomllib is None:
        # Python 3.10 fallback — manual TOML parsing for our simple format
        return _parse_config_manual(config_path, root)

    try:
        data = tomllib.loads(config_path.read_text(encoding="utf-8"))
        section = data.get("agentsync", {})
        cfg.version = section.get("version", cfg.version)
        cfg.canonical = section.get("canonical", cfg.canonical)
        cfg.tools = section.get("tools", cfg.tools)
        cfg.auto_gitignore = section.get("auto_gitignore", cfg.auto_gitignore)
        cfg.warn_unmanaged = section.get("warn_unmanaged", cfg.warn_unmanaged)
    except Exception:
        pass

    return cfg


def _parse_config_manual(config_path: Path, root: Path) -> AgentSyncConfig:
    """Minimal TOML parser for Python 3.10 compatibility. Handles multiline arrays."""
    import re

    cfg = AgentSyncConfig(root=root)
    try:
        text = config_path.read_text(encoding="utf-8")

        # Extract tools array — may span multiple lines: tools = [\n    "x",\n]
        tools_match = re.search(r"tools\s*=\s*\[([^\]]*)\]", text, re.DOTALL)
        if tools_match:
            tools_block = tools_match.group(1)
            tools = re.findall(r'"([^"]+)"', tools_block)
            cfg.tools = tools

        for line in text.splitlines():
            line = line.strip()
            if line.startswith("canonical"):
                parts = line.split("=", 1)
                if len(parts) == 2:
                    cfg.canonical = parts[1].strip().strip('"').strip("'")
            elif line.startswith("auto_gitignore"):
                cfg.auto_gitignore = "true" in line.lower()
    except Exception:
        pass
    return cfg


def is_initialised(root: Path | None = None) -> bool:
    """Check if agentsync has been initialised in this directory."""
    root = root or Path.cwd()
    return (root / CONFIG_FILE).exists() and (root / RULES_FILE).exists()


def read_rules(root: Path | None = None) -> str:
    """Read the canonical rules file."""
    root = root or Path.cwd()
    rules_path = root / RULES_FILE
    if not rules_path.exists():
        raise FileNotFoundError(
            f"Rules file not found at {rules_path}. " "Run `agentsync init` first."
        )
    return rules_path.read_text(encoding="utf-8")


def _replace_tools(content: str, replacement: str, newline: str) -> str:
    """Replace the tools array without touching strings, comments or other tables."""
    import re

    strings = "|".join(
        (
            r'"""(?:\\.|(?!""").)*"{3,5}',
            r"'''(?:(?!''').)*'{3,5}",
            r'"(?:\\.|[^"\\])*"',
            r"'[^']*'",
        )
    )
    tokens = re.finditer(
        r"(?P<table>^[ \t]*\[(?P<table_name>[^\r\n]*?)\][ \t]*(?:#[^\r\n]*)?(?:\r?\n|$))"
        rf"""|(?P<tools>^[ \t]*(?:tools|"tools"|'tools')[ \t]*=[ \t]*\[(?:{strings}|#[^\r\n]*|[^\]"'#])*\])"""
        rf"|#[^\r\n]*|{strings}",
        content,
        re.MULTILINE | re.DOTALL,
    )
    in_agentsync = False
    insertion = None
    for token in tokens:
        if token.group("table") is not None:
            if in_agentsync:
                insertion = token.start()
                break
            in_agentsync = token.group("table_name").strip() in (
                "agentsync",
                '"agentsync"',
                "'agentsync'",
            )
            if in_agentsync:
                insertion = len(content)
        elif in_agentsync and token.group("tools") is not None:
            return content[: token.start()] + replacement + content[token.end() :]

    if insertion is None:
        separator = "" if not content or content.endswith("\n") else newline
        return content + f"{separator}[agentsync]{newline}{replacement}{newline}"
    separator = "" if content[:insertion].endswith("\n") else newline
    return content[:insertion] + separator + replacement + newline + content[insertion:]


def write_config(
    root: Path | None = None,
    tools: list[str] | None = None,
    *,
    preserve_existing: bool = False,
) -> None:
    """Write a config, optionally preserving everything outside the tools array."""
    root = root or Path.cwd()
    config_path = root / CONFIG_FILE
    config_path.parent.mkdir(parents=True, exist_ok=True)
    content = DEFAULT_CONFIG
    if preserve_existing and config_path.exists():
        content = config_path.read_bytes().decode("utf-8")
    if tools is not None:
        import json

        newline = "\r\n" if "\r\n" in content else "\n"
        tool_lines = [f"    {json.dumps(t, ensure_ascii=False)}," for t in tools]
        replacement = newline.join(["tools = [", *tool_lines, "]"])
        content = _replace_tools(content, replacement, newline)
    config_path.write_bytes(content.encode("utf-8"))


def write_rules(content: str | None = None, root: Path | None = None) -> None:
    """Write the canonical rules file."""
    root = root or Path.cwd()
    rules_path = root / RULES_FILE
    rules_path.parent.mkdir(parents=True, exist_ok=True)
    rules_path.write_text(content or DEFAULT_RULES, encoding="utf-8")
